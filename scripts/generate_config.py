    drift_found = False
    for path, expected in targets:
        if not path.exists():
            print(f"[DRIFT] Missing target file: {path.relative_to(ROOT)}")
            drift_found = True
            if not check_only:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected, encoding="utf-8")
                print(f"[GEN] Created {path.relative_to(ROOT)}")
            continue

        existing = path.read_text(encoding="utf-8")
        # Normalize newlines for comparison
        if existing.replace("\r\n", "\n") != expected.replace("\r\n", "\n"):
            print(f"[DRIFT] File content mismatch: {path.relative_to(ROOT)}")
            drift_found = True
            if not check_only:
                path.write_text(expected, encoding="utf-8")
                print(f"[GEN] Updated {path.relative_to(ROOT)}")
        else:
            if not check_only:
                print(f"[OK] Up-to-date: {path.relative_to(ROOT)}")

