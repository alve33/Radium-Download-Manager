    manifest_dev_content = manifest_chr_content

    # 4. Generate package.json & package-lock.json version
    package_json_path = ROOT / "package.json"
    pkg = json.loads(package_json_path.read_text(encoding="utf-8"))
    pkg["version"] = version_str
    package_json_content = json.dumps(pkg, indent=2, ensure_ascii=False) + "\n"

    package_lock_path = ROOT / "package-lock.json"
    package_lock_content = ""
    if package_lock_path.exists():
        pkg_lock = json.loads(package_lock_path.read_text(encoding="utf-8"))
        pkg_lock["version"] = version_str
        if "packages" in pkg_lock and "" in pkg_lock["packages"]:
            pkg_lock["packages"][""]["version"] = version_str
        package_lock_content = json.dumps(pkg_lock, indent=2, ensure_ascii=False) + "\n"

