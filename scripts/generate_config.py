    manifest_ff_path = ROOT / "extension" / "manifest.firefox.json"
    manifest_ff = json.loads(manifest_ff_path.read_text(encoding="utf-8"))
    manifest_ff["name"] = product_name
    manifest_ff["version"] = version_str
    if "browser_specific_settings" in manifest_ff and "gecko" in manifest_ff["browser_specific_settings"]:
        manifest_ff["browser_specific_settings"]["gecko"]["id"] = prod.get("gecko_extension_id", "radium-extension@radiumdownloadmanager.org")
