    # 3. Generate manifests (manifest.chromium.json, manifest.firefox.json, and manifest.json identical to chromium)
    manifest_chr_path = ROOT / "extension" / "manifest.chromium.json"
    manifest_chr = json.loads(manifest_chr_path.read_text(encoding="utf-8"))
